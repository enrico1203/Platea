// Versione: dal tag della release (-PappVersion=0.1.7), altrimenti quella del server in sviluppo.
// versionCode cresce con la versione (0.1.7 → 107), così un APK nuovo si installa sopra il vecchio.
val appVersion = (project.findProperty("appVersion") as String?)?.removePrefix("v") ?: "0.1.27"
val appVersionCode = appVersion.split(".").map { it.toIntOrNull() ?: 0 }.let { (it.getOrElse(0) { 0 } * 10000) + (it.getOrElse(1) { 0 } * 100) + it.getOrElse(2) { 0 } }

// Firma di rilascio facoltativa: keystore.properties (non versionato) con storeFile, storePassword, keyAlias, keyPassword.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

android {
    namespace = "app.platea"
    compileSdk = 35

    defaultConfig {
        applicationId = "app.platea"
        // Fire OS 5 (Fire TV Stick di 2ª generazione) è Android 5.1: API 22.
        minSdk = 22
        targetSdk = 35
        versionCode = appVersionCode
        versionName = appVersion
        vectorDrawables.useSupportLibrary = true
    }

    signingConfigs {
        if (keystoreProps.isNotEmpty()) {
            create("release") {
                storeFile = rootProject.file(keystoreProps.getProperty("storeFile"))
                storePassword = keystoreProps.getProperty("storePassword")
                keyAlias = keystoreProps.getProperty("keyAlias")
                keyPassword = keystoreProps.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.findByName("release") ?: signingConfigs.getByName("debug")
        }
        debug {
            applicationIdSuffix = ".debug"
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions {
        jvmTarget = "17"
    }
    buildFeatures {
        compose = true
        buildConfig = true
    }
    packaging {
        resources.excludes += setOf("/META-INF/{AL2.0,LGPL2.1}", "/META-INF/versions/9/previous-compilation-data.bin")
    }
    lint {
        abortOnError = false
    }
    testOptions {
        unitTests.isReturnDefaultValues = true
        unitTests.isIncludeAndroidResources = true
        unitTests.all {
            // Schermate disegnate sulla JVM (Robolectric) collegate a un server di prova: vedi ScreensTest.
            it.systemProperty("platea.server", project.findProperty("plateaServer") ?: "")
            it.systemProperty("roborazzi.test.record", "true")
            it.maxHeapSize = "2g"
            // Un test bloccato (server di prova che non risponde, Robolectric fermo) non deve tenere ferma la build:
            // il task si interrompe dopo 15 minuti, ogni singolo test dopo 2 (regola JUnit nei test).
            it.timeout.set(Duration.ofMinutes(15))
        }
    }
}

